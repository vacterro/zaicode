/**
 * T-312 / SRC-227 — Smart Text Attachment Expansion & Round-Trip Editing.
 *
 * Requirements:
 *  1. Canonical Edit Model: Working drafts, dirty tracking, transactional materialization on save.
 *  2. Composer Inline Expansion: Collapse retains working copy; Remove deletes; Cancel/Escape discard.
 *  3. Session Message Editing: Copy-On-Write semantics, reads via context.readAttachment, non-destructive,
 *     preserves array ordering, visible error indications.
 *  4. Three-Word Auto-Filename Generation: First three words, Unicode-safe, Windows illegal characters
 *     and reserved names sanitized, safe fallback. Auto-generated filenames update on edit; user-uploaded
 *     files keep original names.
 *  5. Command Isolation: Text attachment edits never trigger Auto-Goal or execute as slash commands.
 */
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";

import {
  deriveTextAttachmentFilename,
  isAutoGeneratedAttachmentRef,
} from "@/lib/chatAttachmentMetadata.js";

const src = (path: string) => readFileSync(join(import.meta.dirname, "../src", path), "utf8");

test("T-312 Section D: 3-word filename derivation with English content", () => {
  const result = deriveTextAttachmentFilename(
    "Implement Smart Code Refactoring for large projects",
  );
  assert.equal(result, "Implement Smart Code.txt");
});

test("T-312 Section D: 3-word filename derivation with Cyrillic / Unicode content", () => {
  const result = deriveTextAttachmentFilename(
    "Нужно исправить отправку команд в приложении",
  );
  assert.equal(result, "Нужно исправить.txt");
});

test("T-312 Section D: Windows reserved device names are sanitized", () => {
  const reserved = ["CON", "PRN", "AUX", "NUL", "COM1", "COM9", "LPT1", "LPT9"];
  for (const name of reserved) {
    const filename = deriveTextAttachmentFilename(name);
    assert.equal(filename, `${name}-file.txt`);
  }
});

test("T-312 Section D: Windows illegal characters and traversal are stripped", () => {
  const dirty = deriveTextAttachmentFilename('../../<illegal>:*?"|stuff');
  assert.equal(dirty, "illegal stuff.txt");
  assert.doesNotMatch(dirty, /[<>:"/\\|?*]/);
  assert.doesNotMatch(dirty, /\.\./);
});

test("T-312 Section D: Empty or whitespace content falls back safely", () => {
  assert.equal(deriveTextAttachmentFilename(""), "pasted-text.txt");
  assert.equal(deriveTextAttachmentFilename("   \t\n  "), "pasted-text.txt");
  assert.equal(deriveTextAttachmentFilename("!!! ???"), "pasted-text.txt");
});

test("T-312 Section D: Length and word boundaries respected", () => {
  // Only 1 word
  assert.equal(deriveTextAttachmentFilename("SingleWord"), "SingleWord.txt");
  // 2 words
  assert.equal(deriveTextAttachmentFilename("Two Words"), "Two Words.txt");
  // Long word capped at maxBaseLength (default 20)
  const longWord = "Supercalifragilisticexpialidocious";
  assert.equal(deriveTextAttachmentFilename(longWord), `${longWord.slice(0, 20)}.txt`);
});

test("T-312 Section D: Auto-generated attachment detection vs user-uploaded files", () => {
  // Auto-generated references
  assert.equal(
    isAutoGeneratedAttachmentRef({ fileName: "pasted-text.txt" }),
    true,
  );
  assert.equal(
    isAutoGeneratedAttachmentRef({ fileName: "pasted-text-20261012-140000.txt" }),
    true,
  );
  assert.equal(
    isAutoGeneratedAttachmentRef({
      ref: "/data/tmp/paste-attachments/2026-10-12/Implement Smart Code-a1b2c3d4.txt",
      fileName: "Implement Smart Code.txt",
    }),
    true,
  );

  // User-uploaded files
  assert.equal(
    isAutoGeneratedAttachmentRef({
      ref: "/workspace/project/notes.txt",
      fileName: "notes.txt",
    }),
    false,
  );
  assert.equal(
    isAutoGeneratedAttachmentRef({
      ref: "session://blob/abc12345",
      fileName: "schema.sql",
    }),
    false,
  );
});

