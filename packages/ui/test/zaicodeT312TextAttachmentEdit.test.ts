test("T-312 Section E & F: Atomic Repackaging and multi-attachment array order preservation", () => {
  // Simulates copy-on-write immutability & order preservation
  const originalAttachments = [
    { ref: "/old/file1.txt", fileName: "First.txt", mime: "text/plain", bytes: 100 },
    { ref: "/old/file2.txt", fileName: "Second.txt", mime: "text/plain", bytes: 200 },
    { ref: "/old/file3.txt", fileName: "Third.txt", mime: "text/plain", bytes: 300 },
  ];

  const editedIndex = 1;
  const newContent = "Updated content for the second item";
  const newFilename = deriveTextAttachmentFilename(newContent);
  const newTempFile = {
    localPath: "/tmp/paste-attachments/Updated content for-12345678.txt",
    sizeBytes: Buffer.byteLength(newContent, "utf8"),
  };

  // Replacement without mutation of originals
  const updatedAttachments = [...originalAttachments];
  updatedAttachments[editedIndex] = {
    ref: newTempFile.localPath,
    fileName: newFilename,
    mime: "text/plain",
    bytes: newTempFile.sizeBytes,
  };

  // Verify historical refs are untouched
  assert.equal(originalAttachments[1].ref, "/old/file2.txt");
  assert.equal(originalAttachments[1].fileName, "Second.txt");

  // Verify array ordering and replacement
  assert.equal(updatedAttachments.length, 3);
  assert.equal(updatedAttachments[0].ref, "/old/file1.txt");
  assert.equal(updatedAttachments[1].ref, newTempFile.localPath);
  assert.equal(updatedAttachments[1].fileName, "Updated content for.txt");
  assert.equal(updatedAttachments[2].ref, "/old/file3.txt");
});

test("T-312 Section G: Command Isolation — text attachment content never triggers commands", () => {
  const contentWithCommand = "/goal do something dangerous\n/clear\n/reset";
  const filename = deriveTextAttachmentFilename(contentWithCommand);
  // Word match [\p{L}\p{N}]+ strips the leading slashes into normal words
  assert.equal(filename, "goal do something.txt");
  assert.doesNotMatch(filename, /^\//);
});
