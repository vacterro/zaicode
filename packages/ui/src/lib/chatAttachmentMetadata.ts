const SPREADSHEET_CLIPBOARD_HTML_PATTERN =
  /(?:<table\b|urn:schemas-microsoft-com:office:excel|\bExcel\.Sheet\b|\bMicrosoft\s+Excel\b|\bmso-(?:number-format|displayed-decimal-separator)\b)/iu;

/**
 * Excel 会同时写入 plain text、HTML 和一张合成 PNG；有表格文本证据时应让文本获胜。
 * 制表符覆盖多列复制，Excel HTML 标记覆盖单单元格和单列复制。
 */
export function shouldPreferSpreadsheetClipboardText(text: string, html: string): boolean {
  if (text.length === 0) return false;
  return text.includes("\t") || SPREADSHEET_CLIPBOARD_HTML_PATTERN.test(html);
}

export function countClipboardTextLines(text: string): number {
  if (text.length === 0) {
    return 0;
  }

  let lines = 1;
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    if (char === "\n") {
      lines += 1;
      continue;
    }
    if (char === "\r") {
      lines += 1;
      if (text[index + 1] === "\n") {
        index += 1;
      }
    }
  }
  return lines;
}

export function deriveTextAttachmentFilename(
  content: string,
  options: {
    maxWords?: number;
    maxBaseLength?: number;
    fallback?: string;
  } = {},
): string {
  const maxWords = options.maxWords ?? 3;
  const maxBaseLength = options.maxBaseLength ?? 20;
  const fallback = options.fallback ?? "pasted-text.txt";

  if (!content || typeof content !== "string" || !content.trim()) {
    return fallback;
  }

  const words = content.trim().match(/[\p{L}\p{N}]+/gu);
  if (!words || words.length === 0) {
    return fallback;
  }

  const selectedWords: string[] = [];
  for (let i = 0; i < Math.min(words.length, maxWords); i += 1) {
    const word = words[i];
    if (!word) break;
    const candidate = [...selectedWords, word].join(" ");
    if (candidate.length <= maxBaseLength) {
      selectedWords.push(word);
    } else {
      if (selectedWords.length === 0) {
        selectedWords.push(word.slice(0, maxBaseLength));
      }
      break;
    }
  }

  if (selectedWords.length === 0) {
    return fallback;
  }

  let baseName = selectedWords.join(" ").trim();
  // oxlint-disable-next-line eslint(no-control-regex)
  baseName = baseName.replace(/[<>:"/\\|?*\x00-\x1f]/gu, "").trim();
  baseName = baseName.replace(/[. ]+$/u, "").trim();

  const WINDOWS_RESERVED = /^(CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])$/i;
  if (!baseName || WINDOWS_RESERVED.test(baseName)) {
    baseName = `${baseName || "text"}-file`;
  }

  return `${baseName}.txt`;
}

export function isAutoGeneratedAttachmentRef(attachment: { ref?: string; fileName?: string }): boolean {
  const fileName = attachment.fileName ?? "";
  const ref = attachment.ref ?? "";
  if (
    fileName === "pasted-text.txt" ||
    fileName.startsWith("pasted-text-") ||
    fileName.startsWith("text-file")
  ) {
    return true;
  }
  if (ref.includes("paste-attachments")) {
    return true;
  }
  return false;
}

export function createClipboardTextAttachmentFilename(now: Date = new Date(), text?: string): string {
  if (typeof text === "string" && text.trim().length > 0) {
    return deriveTextAttachmentFilename(text);
  }
  const pad = (value: number) => String(value).padStart(2, "0");
  const date = [now.getFullYear(), pad(now.getMonth() + 1), pad(now.getDate())].join("");
  const time = [now.getHours(), now.getMinutes(), now.getSeconds()].map(pad).join("");
  return `pasted-text-${date}-${time}.txt`;
}

export function basenameFromPath(path: string): string {
  return path.split(/[\\/]/u).filter(Boolean).pop() ?? path;
}

export function inferAttachmentMimeType(filename: string): string {
  const extension = filename.split(".").pop()?.toLocaleLowerCase() ?? "";
  if (extension === "md") return "text/markdown";
  if (extension === "json") return "application/json";
  if (extension === "csv") return "text/csv";
  if (extension === "txt" || extension === "log") return "text/plain";
  if (extension === "png") return "image/png";
  if (extension === "jpg" || extension === "jpeg") return "image/jpeg";
  if (extension === "gif") return "image/gif";
  if (extension === "webp") return "image/webp";
  if (extension === "svg") return "image/svg+xml";
  if (extension === "mp4") return "video/mp4";
  if (extension === "m4v") return "video/x-m4v";
  if (extension === "mov") return "video/quicktime";
  if (extension === "webm") return "video/webm";
  if (extension === "mkv") return "video/x-matroska";
  if (extension === "avi") return "video/x-msvideo";
  if (extension === "pdf") return "application/pdf";
  return "application/octet-stream";
}

export function isTextLikeAttachment(attachment: { filename: string; mimeType: string }): boolean {
  const mimeType = attachment.mimeType || inferAttachmentMimeType(attachment.filename);
  if (mimeType.startsWith("text/")) {
    return true;
  }

  return /\.(cjs|conf|cpp|cs|css|csv|go|h|hpp|html|ini|java|js|json|jsx|log|md|mjs|py|rs|sh|sql|toml|ts|tsx|txt|xml|yaml|yml)$/iu.test(
    attachment.filename,
  );
}

export function formatAttachmentSize(sizeBytes: number): string {
  const mib = sizeBytes / (1024 * 1024);
  return mib >= 1 ? `${mib.toFixed(mib >= 10 ? 0 : 1)} MB` : `${Math.ceil(sizeBytes / 1024)} KB`;
}
