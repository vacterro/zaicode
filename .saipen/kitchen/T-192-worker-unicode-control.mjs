import {createRequire} from 'node:module';
import {mkdtemp,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
const root=resolve(import.meta.dirname,'../..'),product=join(root,'zcode');
const require=createRequire(join(product,'packages/services/package.json'));
const {build}=require('esbuild'),pty=require('node-pty');
const scratch=await mkdtemp(join(tmpdir(),'zaicode-worker-unicode-'));
const compiled=join(scratch,'worker.mjs');
const broker=join(scratch,'broker.mjs');
await build({entryPoints:[join(product,'packages/services/src/terminal/workerTerminalBroker.ts')],outfile:broker,format:'esm',platform:'node',bundle:true,banner:{js:"import {createRequire as fixtureRequire} from 'node:module';const require=fixtureRequire(import.meta.url);"},plugins:[{name:'native',setup(b){b.onResolve({filter:/^node-pty$/},()=>({path:pathToFileURL(require.resolve('node-pty')).href,external:true}))}}]});
await build({entryPoints:[join(product,'packages/services/src/terminal/workerTerminalProcess.ts')],outfile:compiled,format:'esm',platform:'node',bundle:true,banner:{js:"import {createRequire as fixtureRequire} from 'node:module';const require=fixtureRequire(import.meta.url);"}});
const {createWorkerTerminalProcess,externalClientCommand}=await import(pathToFileURL(compiled));
let appOut='',externalOut='',external;
const sleep=ms=>new Promise(res=>setTimeout(res,ms));
const wait=async fn=>{for(let i=0;i<800;i++){if(fn())return;await sleep(20)}throw new Error('control timeout')};
const worker=await createWorkerTerminalProcess({shell:'powershell.exe',cwd:product,cols:140,rows:24,env:process.env},{entryPath:pathToFileURL(broker),launchClient:async launch=>{
  external=pty.spawn('powershell.exe',['-NoLogo','-NoProfile','-EncodedCommand',Buffer.from(externalClientCommand(launch),'utf16le').toString('base64')],{cwd:product,env:process.env,cols:140,rows:24,useConpty:true,useConptyDll:false});
  external.onData(text=>externalOut+=text);
}});
worker.onData(text=>appOut+=text);
await wait(()=>/PS .*?>/.test(appOut));
worker.write("Write-Output ('MODE:'+([bool](Get-Module PSReadLine))+':'+$env:TERM);Write-Output ('BEFORE:'+'tere-привет-🌙')\r");
await sleep(700);
await worker.extractToPowerShell();worker.kill();
external.write("Write-Output ('AFTER:'+'tere-привет-🌙');exit\r");
await sleep(1500);
await writeFile(join(root,'.saipen/evidence/T-192-worker-unicode-control.json'),JSON.stringify({appOut,externalOut},null,2));
console.log(JSON.stringify({appOut:appOut.slice(-1800),externalOut:externalOut.slice(-1800)}));
process.exit(0);
