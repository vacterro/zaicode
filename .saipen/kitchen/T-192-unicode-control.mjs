import { createRequire } from 'node:module';
import { createServer } from 'node:net';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { randomBytes } from 'node:crypto';
import { pathToFileURL } from 'node:url';
const root=resolve(import.meta.dirname,'../..'), product=join(root,'zcode');
const require=createRequire(join(product,'packages/services/package.json'));
const nodePty=require('node-pty'), {build}=require('esbuild');
const scratch=await mkdtemp(join(tmpdir(),'zaicode-unicode-control-'));
const compiled=join(scratch,'console.mjs');
await build({entryPoints:[join(product,'packages/services/src/terminal/workerTerminalConsole.ts')],outfile:compiled,format:'esm',platform:'node',bundle:true});
const {workerTerminalConsoleCommand}=await import(pathToFileURL(compiled));
const sleep=ms=>new Promise(res=>setTimeout(res,ms));
const wait=async fn=>{for(let i=0;i<500;i++){if(fn())return;await sleep(20)}throw new Error('control timeout')};
let baseline='';
const plain=nodePty.spawn('powershell.exe',[],{cwd:scratch,env:process.env,cols:140,rows:24,useConpty:true,useConptyDll:false});
plain.onData(text=>baseline+=text);
await wait(()=>/PS .*?>/.test(baseline));
plain.write("Write-Output ('BASE:'+'tere-привет-🌙'); exit\r");
await sleep(1000);
const token=randomBytes(32).toString('hex'),lease=randomBytes(32).toString('hex');
const pipe=`\\\\.\\pipe\\zaicode-worker-${token.slice(0,24)}`,config=join(scratch,'terminal.json');
await writeFile(config,JSON.stringify({pipe,token}));
let peer,welcomed=false,received='',consoleOutput='';const writes=[];
const server=createServer(socket=>{peer=socket;let buffer='';socket.setEncoding('utf8');socket.on('data',data=>{buffer+=data;let end;while((end=buffer.indexOf('\n'))>=0){const message=JSON.parse(buffer.slice(0,end));buffer=buffer.slice(end+1);if(message.type==='hello'){socket.write(JSON.stringify({type:'welcome',pid:1})+'\n');welcomed=true;}if(message.type==='write'){received+=message.data;writes.push({data:message.data,codepoints:Array.from(message.data).map(c=>c.codePointAt(0).toString(16))});}}})});
await new Promise(res=>server.listen(pipe,res));
const client=nodePty.spawn('powershell.exe',['-NoLogo','-NoProfile','-EncodedCommand',Buffer.from(workerTerminalConsoleCommand(config,lease),'utf16le').toString('base64')],{cwd:scratch,env:process.env,cols:140,rows:24,useConpty:true,useConptyDll:process.env.T192_CONSOLE_DLL==='1'});
client.onData(text=>consoleOutput+=text);
await wait(()=>welcomed);
client.write('WIRE:tere-привет-🌙\r');
await sleep(1000);
peer.write(JSON.stringify({type:'exit',code:0})+'\n');
await sleep(500);peer.destroy();server.close();
const result={baseline,wire:received,wireCodepoints:Array.from(received).map(c=>c.codePointAt(0).toString(16)),consoleOutput,writes};
await writeFile(join(root,`.saipen/evidence/T-192-unicode-control-${process.env.T192_CONSOLE_DLL||'0'}.json`),JSON.stringify(result,null,2));
console.log(JSON.stringify({wire:received,writes}));
process.exit(0);
